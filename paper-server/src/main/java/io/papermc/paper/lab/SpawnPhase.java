package io.papermc.paper.lab;

/**
 * Фаза тика относительно переписи мобов и спавна.
 *
 * <p>Локальные счётчики Paper — <b>фазовый снимок</b>, а не непрерывная перепись живых мобов.
 * Перепись целиком выполняется в начале {@code ServerChunkCache.tickChunks} (профилерная
 * секция {@code naturalSpawnCount}), спавн — после неё. Поэтому снимки «до» и «после» обязаны
 * иметь разные метки: смерть моба позже в этом же тике не обязана немедленно изменить счётчик
 * движка.
 */
public enum SpawnPhase {

    /**
     * Фаза неизвестна: хук в движке не выполнялся в этом тике либо инструментарий был выключен.
     * Показывать именно как «неизвестно», а не подставлять другую фазу.
     */
    UNKNOWN("unknown"),

    /**
     * До сброса {@code mobCounts} и спада {@code mobBackoffCounts}. Значения относятся
     * к предыдущему тику.
     */
    BEFORE_CENSUS("before_census"),

    /**
     * Перепись выполнена, спавн ещё не начинался. Это единственная фаза, в которой
     * {@code mobCounts} отражает полный набор учтённых сущностей текущего тика.
     */
    AFTER_CENSUS("after_census"),

    /**
     * Проход спавна по чанкам завершён. {@code mobBackoffCounts} мог вырасти от неудачных
     * попыток, а вновь созданные мобы ещё не попали в {@code mobCounts} — они будут учтены
     * только следующей переписью.
     */
    AFTER_SPAWN("after_spawn");

    private final String id;

    SpawnPhase(final String id) {
        this.id = id;
    }

    public String id() {
        return this.id;
    }
}
